#include <iostream>
#include <clocale>
using namespace std;

int main()
{
    setlocale(LC_ALL, "Russian");

    // Задание 1: калькулятор.
    // Объявляем переменные для двух чисел и знака операции.
    double a, b;
    char op;

    // Просим пользователя ввести два числа и знак.
    cout << "Задание 1. Введите два числа: ";
    cin >> a >> b;
    cout << "Введите знак операции (+, -, *, /, %): ";
    cin >> op;

    // Задается условие выбора (проверяем знак операции).
    switch (op)
    {
        // Если введен плюс, складываем числа.
        case '+':
            cout << "Результат: " << a + b << endl;
            break;

        // Если введен минус, вычитаем второе число из первого.
        case '-':
            cout << "Результат: " << a - b << endl;
            break;

        // Если введена звездочка, перемножаем числа.
        case '*':
            cout << "Результат: " << a * b << endl;
            break;

        // Если введен слэш, делим первое число на второе (делить на ноль нельзя).
        case '/':
            if (b == 0)
            {
                cout << "Ошибка: на ноль делить нельзя!" << endl;
            }
            else
            {
                cout << "Результат: " << a / b << endl;
            }
            break;

        // Если введен процент, находим остаток от деления (только для целых чисел).
        case '%':
            if ((int)b == 0)
            {
                cout << "Ошибка: на ноль делить нельзя!" << endl;
            }
            else
            {
                cout << "Результат: " << (int)a % (int)b << endl;
            }
            break;

        // Если введен любой другой знак, выводим сообщение об ошибке.
        default:
            cout << "Ошибка: такого знака операции нет!" << endl;
            break;
    }

    // Задание 2: день недели.
    // Объявляем переменную для номера дня.
    int day;

    // Просим пользователя ввести число от 1 до 7.
    cout << endl << "Задание 2. Введите номер дня недели (от 1 до 7): ";
    cin >> day;

    // Задается условие выбора (проверяем номер дня).
    switch (day)
    {
        // Если введена единица, выводим понедельник.
        case 1:
            cout << "Понедельник" << endl;
            break;

        // Если введена двойка, выводим вторник.
        case 2:
            cout << "Вторник" << endl;
            break;

        // Если введена тройка, выводим среду.
        case 3:
            cout << "Среда" << endl;
            break;

        // Если введена четверка, выводим четверг.
        case 4:
            cout << "Четверг" << endl;
            break;

        // Если введена пятерка, выводим пятницу.
        case 5:
            cout << "Пятница" << endl;
            break;

        // Если введена шестерка, выводим субботу.
        case 6:
            cout << "Суббота" << endl;
            break;

        // Если введена семерка, выводим воскресенье.
        case 7:
            cout << "Воскресенье" << endl;
            break;

        // Если число вне диапазона от 1 до 7, выводим сообщение об ошибке.
        default:
            cout << "Ошибка: число должно быть от 1 до 7!" << endl;
            break;
    }

    // Задание 3: собственное задание.
    // Текст задания: пользователь вводит номер месяца (от 1 до 12),
    // программа выводит, к какому времени года относится этот месяц.
    // Если номер месяца неправильный, выводится сообщение об ошибке.
    // Объявляем переменную для номера месяца.
    int month;

    // Просим пользователя ввести номер месяца.
    cout << endl << "Задание 3. Введите номер месяца (от 1 до 12): ";
    cin >> month;

    // Задается условие выбора (проверяем номер месяца).
    switch (month)
    {
        // Если месяц 12, 1 или 2, значит сейчас зима.
        case 12:
        case 1:
        case 2:
            cout << "Зима" << endl;
            break;

        // Если месяц 3, 4 или 5, значит сейчас весна.
        case 3:
        case 4:
        case 5:
            cout << "Весна" << endl;
            break;

        // Если месяц 6, 7 или 8, значит сейчас лето.
        case 6:
        case 7:
        case 8:
            cout << "Лето" << endl;
            break;

        // Если месяц 9, 10 или 11, значит сейчас осень.
        case 9:
        case 10:
        case 11:
            cout << "Осень" << endl;
            break;

        // Если введено любое другое число, выводим сообщение об ошибке.
        default:
            cout << "Ошибка: в году только 12 месяцев!" << endl;
            break;
    }

    return 0;
}
